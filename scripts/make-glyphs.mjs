// Generates public/js/glyphs.js from the public-domain Hershey "Sans 1-stroke"
// font (futural). The result is a clean, Arial-like skeleton with the
// single-storey handwritten a/g used by the practice guide.
//
// Source data: scripts/hershey-sans.json (from the MIT-licensed hersheytext
// package; the Hershey glyph data itself is public domain).
//
// Usage: npm run glyphs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const font = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts', 'hershey-sans.json'), 'utf8'));

const CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';
const SCALE = 0.0285;
const BASELINE = 0.765;
const FONT_BASELINE = 22; // y of the baseline in the Hershey source

// Reorder strokes to the order a child is normally taught.
const REVERSE = new Set(['a', 'd', 'g', 'q', 'i', 'j', 'T']);

function parseStrokes(d) {
  const strokes = [];
  for (const part of d.split('M').filter(Boolean)) {
    const numbers = part
      .replace(/L/g, ' ')
      .trim()
      .split(/[\s,]+/)
      .map(Number)
      .filter(Number.isFinite);
    const points = [];
    for (let i = 0; i + 1 < numbers.length; i += 2) points.push([numbers[i], numbers[i + 1]]);
    if (points.length) strokes.push(points);
  }
  return strokes;
}

function convert(ch) {
  const glyph = font.chars[ch.charCodeAt(0) - 33];
  if (!glyph) return null;
  let strokes = parseStrokes(glyph.d);
  if (!strokes.length) return null;

  if (REVERSE.has(ch)) strokes = [...strokes].reverse();
  if (ch === 'Z' && strokes.length === 3) {
    // diagonal, top, bottom → top, diagonal, bottom
    strokes = [strokes[1], strokes[0], strokes[2]];
  }

  // Teach straight segments as their own strokes instead of one continuous
  // polyline (4 = diagonal + bar + stem, 5 = bar + stem + bowl, 7 = bar first).
  if (ch === '4' && strokes.length === 2) {
    const [top, corner, right] = strokes[0];
    strokes = [[top, corner], [corner, right], strokes[1]];
  }
  if (ch === '5' && strokes.length === 1) {
    const s = strokes[0];
    strokes = [[s[0], s[1]], [s[1], s[2]], s.slice(2)];
  }
  if (ch === '7' && strokes.length === 2) {
    strokes = [strokes[1], strokes[0]];
  }

  const xs = strokes.flat().map((p) => p[0]);
  const minX = Math.min(...xs);
  const maxX = Math.max(...xs);
  const cx = (minX + maxX) / 2;

  return strokes.map((stroke) =>
    stroke.map(([x, y]) => [
      +(0.5 + (x - cx) * SCALE).toFixed(3),
      +(BASELINE + (y - FONT_BASELINE) * SCALE).toFixed(3),
    ]),
  );
}

const glyphs = {};
for (const ch of CHARS) {
  const converted = convert(ch);
  if (!converted) throw new Error(`Missing glyph: ${ch}`);
  glyphs[ch] = converted;
}

const body = Object.entries(glyphs)
  .map(([ch, strokes]) => {
    const key = /[A-Za-z]/.test(ch) ? ch : `'${ch}'`;
    const strokeText = strokes
      .map((stroke) => `[${stroke.map(([x, y]) => `[${x},${y}]`).join(',')}]`)
      .join(',\n    ');
    return `  ${key}: [\n    ${strokeText},\n  ],`;
  })
  .join('\n');

const out = `// Generated by scripts/make-glyphs.mjs — do not edit by hand.
// Hershey "Sans 1-stroke" letterforms (public domain), normalised to a 0..1
// practice box with the baseline at ${BASELINE}. Single-storey a and g.// Run \`npm run glyphs\` to regenerate.

export const GLYPHS = {
${body}
};

export function latinStrokes(ch) {
  return GLYPHS[ch] || null;
}
`;

fs.writeFileSync(path.join(ROOT, 'public', 'js', 'glyphs.js'), out);
console.log(`Wrote public/js/glyphs.js (${Object.keys(glyphs).length} glyphs)`);
