export const PUNCTUATION_CLASS = '[，。、；：？！“”‘’（）《》【】…—～·,.;:!?"-]';

export function isPunctuation(ch) {
  return Object.prototype.hasOwnProperty.call(GLYPHS, ch);
}

/** Stroke medians for a punctuation mark, or null. */
export function punctuationStrokes(ch) {
  const strokes = GLYPHS[ch];
  return strokes ? strokes.map((stroke) => stroke.map(([x, y]) => [x, y])) : null;
}
