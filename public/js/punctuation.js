// Hand-made stroke guides for punctuation (标点符号), used when the parent
// turns on "practise punctuation". Coordinates are normalised to a 田字格
// (0..1), one polyline per stroke; a single point means a dot/tap.

const round = (v) => Math.round(v * 10000) / 10000;

/** A hollow circle, drawn from the top clockwise (the Chinese full stop). */
function circle(cx, cy, r, steps = 16) {
  const points = [];
  for (let i = 0; i <= steps; i += 1) {
    const angle = -Math.PI / 2 + (i / steps) * Math.PI * 2;
    points.push([round(cx + r * Math.cos(angle)), round(cy + r * Math.sin(angle))]);
  }
  return points;
}

