const circle = (cx, cy, rx, ry, steps = 12) => {
  const pts = [];
  for (let i = 0; i <= steps; i += 1) {
    const t = -Math.PI / 2 + (i / steps) * Math.PI * 2;
    pts.push([+(cx + Math.cos(t) * rx).toFixed(3), +(cy + Math.sin(t) * ry).toFixed(3)]);
  }
  return pts;
};

